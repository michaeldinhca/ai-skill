#!/usr/bin/env python3
"""Build one self-contained index.html preview for a {PREFIX}-ghl-site project folder.

Usage:  python build_preview.py <path-to-site-folder> [--name "Client Name"]

Reads global/01-03, every pages/*.html and every drafts/*.html, and writes:
  index.html  one standalone file (all CSS/JS inlined, no local asset paths) that shows one
              page at a time, like GHL does: head code, header, the page body, footer.
              ?page=<slug> picks a page, ?page=draft:<slug> a Phase 2 mockup, ?bar=0 hides
              the preview bar. An unknown page shows pages/404.html, like the live site.
  site.json   small manifest (name, pages, drafts, updated) for tools that list previews.

index.html is always generated. Never edit it by hand; rerun this script instead. A hand-made
index.html found in the folder is moved to archive/ rather than overwritten.
Python standard library only.
"""
import argparse
import datetime
import json
import pathlib
import re
import shutil
import sys

MARKER = "<!-- ghl-site-preview: generated by build_preview.py, do not edit by hand, rerun it -->"
LAST = {"404": 1, "thank-you": 2}


def read(path):
    return path.read_text(encoding="utf-8") if path.exists() else ""


def js_value(obj):
    # JSON is valid JS; escaping "<" keeps </script> and <!-- inside strings from ending the block.
    return json.dumps(obj, ensure_ascii=False).replace("<", "\\u003c")


def label(slug):
    if slug == "home":
        return "Home"
    if slug == "404":
        return "404"
    return slug.replace("-", " ").capitalize()


def page_order(slug):
    return (0 if slug == "home" else 1 + LAST.get(slug, 0), slug)


def site_name(folder, given):
    if given:
        return given
    for guide in sorted(folder.glob("*-DESIGN-GUIDELINES.md")):
        m = re.search(r"^#\s+(.+)$", read(guide), re.M)
        if m:
            return re.sub(r"\s*(design guidelines?)\s*$", "", m.group(1), flags=re.I).strip() or m.group(1).strip()
    return folder.name.removesuffix("-ghl-site")


ROUTER = r"""
(function () {
  var D = window.__GHL_PREVIEW__;
  var q = new URLSearchParams(location.search);
  var showBar = q.get('bar') !== '0';
  var pageKeys = D.order;
  var draftKeys = Object.keys(D.drafts).sort();
  var key = q.get('page');
  if (!key) key = pageKeys.length ? pageKeys[0] : (draftKeys.length ? 'draft:' + draftKeys[0] : '');
  var isDraft = key.indexOf('draft:') === 0;
  var slug = isDraft ? key.slice(6) : key;
  var html;

  if (isDraft && D.drafts[slug] != null) {
    document.write('<iframe id="ghl-preview-draft" title="Draft preview" style="position:fixed;inset:0;width:100%;height:100%;border:0;background:#fff"></iframe>');
    document.addEventListener('DOMContentLoaded', function () {
      var f = document.getElementById('ghl-preview-draft');
      if (f) f.srcdoc = D.drafts[slug];
    });
  } else {
    isDraft = false;
    html = D.pages[slug];
    if (html == null) html = D.pages['404'] != null ? D.pages['404'] : '<p style="padding:160px 24px;text-align:center;font:16px system-ui">No page "' + slug.replace(/</g, '&lt;') + '" in this build.</p>';
    document.write(D.header + html + D.footer);
  }
  document.title = D.name + ' | ' + (isDraft ? 'Draft: ' : '') + (D.labels[slug] || slug);

  function go(target, hash) {
    var p = new URLSearchParams(location.search);
    p.set('page', target);
    location.href = '?' + p.toString() + (hash ? '#' + hash : '');
  }

  // Site links are written for the live domain ("/about", "/#services"). Route them to pages here.
  document.addEventListener('click', function (e) {
    var a = e.target && e.target.closest ? e.target.closest('a[href]') : null;
    if (!a || a.target === '_blank' || e.defaultPrevented) return;
    var href = a.getAttribute('href');
    if (!href || href.charAt(0) !== '/' || href.charAt(1) === '/') return;
    var parts = href.split('#');
    var dest = parts[0].replace(/[?].*$/, '').replace(/^\/+|\/+$/g, '') || 'home';
    var hash = parts[1] || '';
    e.preventDefault();
    if (dest === slug && !isDraft) {
      if (hash) location.hash = hash;
      else window.scrollTo(0, 0);
      return;
    }
    go(dest, hash);
  }, true);

  if (!showBar) return;
  document.addEventListener('DOMContentLoaded', function () {
    var bar = document.createElement('nav');
    bar.setAttribute('aria-label', 'Preview pages');
    bar.style.cssText = 'position:fixed;left:50%;bottom:16px;transform:translateX(-50%);z-index:2147483000;display:flex;flex-wrap:wrap;justify-content:center;gap:4px;max-width:calc(100vw - 180px);padding:6px;border-radius:14px;background:rgba(17,17,17,.88);box-shadow:0 6px 24px rgba(0,0,0,.25);font:500 12px/1 system-ui,sans-serif';
    function pill(text, target, active, draft) {
      var b = document.createElement('button');
      b.type = 'button';
      b.textContent = text;
      b.style.cssText = 'all:unset;cursor:pointer;padding:7px 10px;border-radius:9px;color:' + (active ? '#111' : '#eee') + ';background:' + (active ? '#fff' : 'transparent') + (draft ? ';font-style:italic' : '');
      b.addEventListener('click', function () { go(target); });
      bar.appendChild(b);
    }
    pageKeys.forEach(function (k) { pill(D.labels[k], k, !isDraft && k === slug); });
    draftKeys.forEach(function (k) { pill('Draft: ' + (D.labels[k] || k), 'draft:' + k, isDraft && k === slug, true); });
    document.body.appendChild(bar);
  });
})();
"""


def build(folder, name=None):
    folder = pathlib.Path(folder).resolve()
    if not folder.is_dir():
        sys.exit(f"Not a folder: {folder}")
    g = folder / "global"
    head = read(g / "01-site-head-code.html")
    header = read(g / "02-global-header.html")
    footer = read(g / "03-global-footer.html")
    pages = {p.stem: read(p) for p in sorted((folder / "pages").glob("*.html"))}
    drafts = {p.stem: read(p) for p in sorted((folder / "drafts").glob("*.html"))}
    if not pages and not drafts:
        sys.exit("Nothing to preview: no pages/*.html and no drafts/*.html yet.")

    order = sorted(pages, key=page_order)
    labels = {s: label(s) for s in set(pages) | set(drafts)}
    name = site_name(folder, name)
    data = {"name": name, "header": header, "footer": footer, "pages": pages,
            "drafts": drafts, "order": order, "labels": labels}

    index = folder / "index.html"
    if index.exists() and MARKER not in read(index):
        stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
        (folder / "archive").mkdir(exist_ok=True)
        shutil.move(str(index), str(folder / "archive" / f"index-{stamp}.html"))

    doc = f"""<!doctype html>
{MARKER}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>{name}</title>
<style>html,body{{margin:0;padding:0}}</style>
{head}
<script>window.__GHL_PREVIEW__ = {js_value(data)};</script>
</head>
<body>
<script>{ROUTER}</script>
</body>
</html>
"""
    index.write_text(doc, encoding="utf-8")

    updated = datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat()
    manifest = {
        "name": name,
        "prefix": folder.name.removesuffix("-ghl-site"),
        "entry": "index.html",
        "updated": updated,
        "pages": [{"slug": s, "label": labels[s], "url": f"index.html?page={s}"} for s in order],
        "drafts": [{"slug": s, "label": labels[s], "url": f"index.html?page=draft:{s}"} for s in sorted(drafts)],
    }
    (folder / "site.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {index} ({len(order)} pages, {len(drafts)} drafts)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("folder")
    ap.add_argument("--name")
    args = ap.parse_args()
    build(args.folder, args.name)

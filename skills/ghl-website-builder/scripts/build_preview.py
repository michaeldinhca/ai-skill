#!/usr/bin/env python3
"""Build the public, crawlable preview of a {PREFIX}-ghl-site project folder.

Usage:  python build_preview.py <path-to-site-folder> [--name "Site Name"]
                                [--base-url https://host/slug/] [--noindex]

Reads global/01-03, every pages/*.html (GHL page bodies) and every drafts/*.html (Phase 2
mockups, full documents) and writes real static HTML at the folder root:

  index.html      the homepage
  <slug>.html     one file per other page (a built page wins over a draft of the same slug)
  sitemap.xml     every indexable page, absolute URLs
  site.json       manifest: name, baseUrl, index, mock, pages, drafts, seo, linkCheck, generated

Every page is complete without JavaScript, so search engines, AI crawlers and link previews
read the real content, and carries: <title>, meta description, robots, canonical, Open Graph,
Twitter card and WebSite/WebPage/BreadcrumbList JSON-LD. Title, description and social image
come from the "GHL page settings" comment at the top of a page file ("SEO title: ...",
"Meta description: ...", "Social image: ...") or from a draft's own <title> and meta tags.

Site links written for the live domain ("/about", "/#services") are rewritten to the static
files in the OUTPUT only; the GHL source files are never changed.

Checks, printed and saved in site.json (exit code 1 if any error; files are still written):
  links  every /slug is a page or draft, every #anchor a real id, no "#" or relative links
  seo    every indexable page has a written title and description and exactly one <h1>

--base-url is the public address of the folder (needed for canonical, og:url and the sitemap).
It is remembered in site.json; the default is https://mockup.ngynsolutions.com/<folder>/.
--noindex marks the whole site noindex (use it for any site showing a real business identity).

Generated files are never edited by hand; rerun this script. A hand-made file in the way is
moved to archive/. Python standard library only.
"""
import argparse
import datetime
import html as htmllib
import json
import pathlib
import re
import shutil
import sys
import urllib.parse

MARKER = "<!-- ghl-site-preview: generated by build_preview.py, do not edit by hand, rerun it -->"
LAST = {"accessibility": 1, "404": 2, "thank-you": 3}
NEVER_INDEX = {"404", "thank-you"}
NOT_LINKED_OK = {"home", "404", "thank-you"}
DEFAULT_HOST = "https://mockup.ngynsolutions.com/"

A_HREF = re.compile(r"""<a\b[^>]*?\bhref\s*=\s*(["'])(.*?)\1""", re.I | re.S)
ID_ATTR = re.compile(r"""\bid\s*=\s*(["'])(.+?)\1""", re.I)
EXTERNAL = ("http://", "https://", "//", "mailto:", "tel:", "sms:", "data:")


def read(path):
    return path.read_text(encoding="utf-8") if path.exists() else ""


def esc(text):
    return htmllib.escape(text or "", quote=True)


def label(slug):
    if slug == "home":
        return "Home"
    if slug == "404":
        return "404"
    return slug.replace("-", " ").capitalize()


def page_order(slug):
    return (0 if slug == "home" else 1 + LAST.get(slug, 0), slug)


def site_name(folder, given, previous):
    if given:
        return given
    if previous.get("name"):
        return previous["name"]
    for guide in sorted(folder.glob("*-DESIGN-GUIDELINES.md")):
        m = re.search(r"^#\s+(.+)$", read(guide), re.M)
        if m:
            return re.sub(r"\s*(design guidelines?)\s*$", "", m.group(1), flags=re.I).strip() or m.group(1).strip()
    return folder.name.removesuffix("-ghl-site")


# ---------- reading SEO settings ----------

def visible_text(markup):
    markup = re.sub(r"<(script|style|template|noscript)\b.*?</\1>", " ", markup, flags=re.I | re.S)
    markup = re.sub(r"<!--.*?-->", " ", markup, flags=re.S)
    return re.sub(r"\s+", " ", htmllib.unescape(re.sub(r"<[^>]+>", " ", markup))).strip()


def clip(text, limit=155):
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:. ") + "."


def first_image(markup):
    m = re.search(r"""<img\b[^>]*?\bsrc\s*=\s*(["'])(https?://[^"']+)\1""", markup, re.I)
    return m.group(2) if m else ""


def settings_from_comment(markup):
    """GHL page settings live in a comment at the top of a page body file."""
    comments = " \n".join(re.findall(r"<!--(.*?)-->", markup[:6000], re.S))

    def grab(pattern):
        m = re.search(pattern, comments, re.I)
        return re.sub(r"\s+", " ", m.group(1)).strip() if m else ""

    # Values run to the end of their line: titles routinely contain " | ".
    return {
        "title": grab(r"SEO title[^:\n]*:[ \t]*([^\n]+)"),
        "description": grab(r"Meta description[^:\n]*:[ \t]*([^\n]+)"),
        "image": grab(r"Social image[^:\n]*:[ \t]*(https?://\S+)"),
    }


def settings_from_document(markup):
    """A draft is a full document; use its own <title> and meta tags."""
    def meta(name):
        for pat in (rf"""<meta\b[^>]*?\b(?:name|property)\s*=\s*["']{name}["'][^>]*?\bcontent\s*=\s*(["'])(.*?)\1""",
                    rf"""<meta\b[^>]*?\bcontent\s*=\s*(["'])(.*?)\1[^>]*?\b(?:name|property)\s*=\s*["']{name}["']"""):
            m = re.search(pat, markup, re.I | re.S)
            if m:
                return htmllib.unescape(m.group(2)).strip()
        return ""

    t = re.search(r"<title[^>]*>(.*?)</title>", markup, re.I | re.S)
    lang = re.search(r"""<html\b[^>]*?\blang\s*=\s*["']([^"']+)["']""", markup, re.I)
    return {
        "title": htmllib.unescape(re.sub(r"\s+", " ", t.group(1))).strip() if t else "",
        "description": meta("description"),
        "image": meta("og:image"),
        "lang": lang.group(1) if lang else "",
    }


# ---------- links ----------

def hrefs(markup):
    return [m.group(2).strip() for m in A_HREF.finditer(markup)]


def ids(markup):
    return {m.group(2) for m in ID_ATTR.finditer(markup)}


def check_links(header, footer, pages, drafts):
    """Every internal link must land on a page or draft, and every #anchor on a real id."""
    broken, linked = [], set()
    chrome_ids = ids(header) | ids(footer)

    def target_ids(slug):
        if slug in pages:
            return ids(pages[slug]) | chrome_ids
        return ids(drafts.get(slug, ""))

    def check(source, href, same_page_ids):
        low = href.lower()
        if low.startswith(EXTERNAL):
            return
        if href in ("", "#"):
            broken.append((source, href, "placeholder link: point it at a real page or section, or remove it"))
        elif low.startswith("javascript:"):
            broken.append((source, href, "javascript: link: use a real href"))
        elif href.startswith("#"):
            if href[1:] not in same_page_ids:
                broken.append((source, href, f"no element with id=\"{href[1:]}\" on this page"))
        elif href.startswith("/"):
            path, _, anchor = href.partition("#")
            slug = path.split("?")[0].strip("/") or "home"
            shown = "" if slug == "home" else slug
            if slug not in pages and slug not in drafts:
                broken.append((source, href, f"no page or draft for /{shown}: build it or change the link"))
                return
            linked.add(slug)
            if anchor and anchor not in target_ids(slug):
                broken.append((source, href, f"page /{shown} has no element with id=\"{anchor}\""))
        else:
            broken.append((source, href, "relative link: write it as /slug the way the live site will"))

    for slug, markup in pages.items():
        for h in hrefs(markup):
            check(f"pages/{slug}.html", h, ids(markup) | chrome_ids)
    for slug, markup in drafts.items():
        for h in hrefs(markup):
            check(f"drafts/{slug}.html", h, ids(markup))
    for fname, markup in (("global/02-global-header.html", header), ("global/03-global-footer.html", footer)):
        for h in hrefs(markup):
            if h.startswith("#") and len(h) > 1:
                missing = [s for s, p in pages.items() if h[1:] not in ids(p) | chrome_ids]
                if missing:
                    broken.append((fname, h, f"bare #anchor in the header/footer is missing on: {', '.join(missing)}; write it as /page#id"))
            else:
                check(fname, h, chrome_ids)

    unlinked = sorted(s for s in set(pages) | set(drafts) if s not in linked and s not in NOT_LINKED_OK)
    seen, unique = set(), []
    for b in broken:
        if b not in seen:
            seen.add(b)
            unique.append(b)
    return unique, unlinked


def rewrite_links(markup, files):
    """Point live-domain links (/about, /#services) at the static files, in the output only."""
    def sub(m):
        href = m.group(2).strip()
        if not href.startswith("/") or href.startswith("//"):
            return m.group(0)
        path, sep, anchor = href.partition("#")
        slug = path.split("?")[0].strip("/") or "home"
        target = files.get(slug) or files.get("404") or "index.html"
        new = ("./" if target == "index.html" else target) + (sep + anchor if sep else "")
        start, end = m.start(2) - m.start(0), m.end(2) - m.start(0)
        return m.group(0)[:start] + new + m.group(0)[end:]

    return A_HREF.sub(sub, markup)


# ---------- output ----------

BAR = r"""
(function () {
  var D = window.__GHL_PREVIEW__, q = new URLSearchParams(location.search);
  var old = q.get('page');
  if (old) {
    var f = D.files[old.replace(/^draft:/, '')];
    if (f && f !== D.current) { location.replace((f === 'index.html' ? './' : f) + location.hash); return; }
  }
  if (q.get('bar') === '0' || D.pages.length < 2) return;
  function add() {
    var bar = document.createElement('nav');
    bar.setAttribute('aria-label', 'Preview pages');
    bar.style.cssText = 'position:fixed;left:50%;bottom:16px;transform:translateX(-50%);z-index:2147482000;display:flex;flex-wrap:wrap;justify-content:center;gap:4px;max-width:calc(100vw - 180px);padding:6px;border-radius:14px;background:rgba(17,17,17,.88);box-shadow:0 6px 24px rgba(0,0,0,.25);font:500 12px/1 system-ui,sans-serif';
    D.pages.forEach(function (p) {
      var a = document.createElement('a'), on = p.file === D.current;
      a.href = p.file === 'index.html' ? './' : p.file;
      a.textContent = p.label;
      if (!p.index) a.rel = 'nofollow';
      if (on) a.setAttribute('aria-current', 'page');
      a.style.cssText = 'padding:7px 10px;border-radius:9px;text-decoration:none;color:' + (on ? '#111' : '#eee') + ';background:' + (on ? '#fff' : 'transparent');
      bar.appendChild(a);
    });
    document.body.appendChild(bar);
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', add); else add();
})();
"""


def og_locale(lang):
    if "-" in lang:
        a, b = lang.split("-", 1)
        return f"{a.lower()}_{b.upper()}"
    return {"fr": "fr_CA"}.get(lang.lower(), "en_CA")


def head_tags(p, site):
    """The SEO / social / AI-crawler block for one page."""
    url = site["base"] + ("" if p["file"] == "index.html" else p["file"])
    indexable = site["index"] and p["index"]
    robots = "index, follow, max-image-preview:large" if indexable else "noindex, follow"
    lines = [
        f"<title>{esc(p['title'])}</title>",
        f'<meta name="description" content="{esc(p["description"])}">',
        f'<meta name="robots" content="{robots}">',
        f'<link rel="canonical" href="{esc(url)}">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{esc(site["name"])}">',
        f'<meta property="og:title" content="{esc(p["title"])}">',
        f'<meta property="og:description" content="{esc(p["description"])}">',
        f'<meta property="og:url" content="{esc(url)}">',
        f'<meta property="og:locale" content="{esc(og_locale(p["lang"]))}">',
    ]
    if p["image"]:
        lines += [f'<meta property="og:image" content="{esc(p["image"])}">',
                  f'<meta property="og:image:alt" content="{esc(p["title"])}">']
    lines += [
        f'<meta name="twitter:card" content="{"summary_large_image" if p["image"] else "summary"}">',
        f'<meta name="twitter:title" content="{esc(p["title"])}">',
        f'<meta name="twitter:description" content="{esc(p["description"])}">',
    ]
    if p["image"]:
        lines.append(f'<meta name="twitter:image" content="{esc(p["image"])}">')

    graph = [
        {"@type": "WebSite", "@id": site["base"] + "#website", "url": site["base"], "name": site["name"],
         "inLanguage": p["lang"]},
        {"@type": "WebPage", "@id": url + "#webpage", "url": url, "name": p["title"],
         "description": p["description"], "isPartOf": {"@id": site["base"] + "#website"}, "inLanguage": p["lang"]},
    ]
    if p["image"]:
        graph[1]["primaryImageOfPage"] = {"@type": "ImageObject", "url": p["image"]}
    if p["file"] != "index.html":
        graph.append({"@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": site["base"]},
            {"@type": "ListItem", "position": 2, "name": p["label"], "item": url}]})
    ld = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False).replace("<", "\\u003c")
    lines.append(f'<script type="application/ld+json">{ld}</script>')
    return "\n".join(lines)


def bar_script(p, site):
    data = {"current": p["file"], "files": site["files"],
            "pages": [{"file": x["file"], "label": x["label"], "index": site["index"] and x["index"]} for x in site["pages"]]}
    return ("<script>window.__GHL_PREVIEW__ = " + json.dumps(data, ensure_ascii=False).replace("<", "\\u003c")
            + ";</script>\n<script>" + BAR + "</script>")


STRIP_FROM_DRAFT = [
    r"<title[^>]*>.*?</title>",
    r"""<meta\b[^>]*?\b(?:name|property)\s*=\s*["'](?:description|robots|og:[^"']+|twitter:[^"']+)["'][^>]*>""",
    r"""<link\b[^>]*?\brel\s*=\s*["']canonical["'][^>]*>""",
]


def render_built(p, site, head, header, footer, body):
    return f"""<!doctype html>
{MARKER}
<html lang="{esc(p['lang'])}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
{head_tags(p, site)}
<style>html,body{{margin:0;padding:0}}</style>
{head}
</head>
<body>
{rewrite_links(header, site['files'])}
{rewrite_links(body, site['files'])}
{rewrite_links(footer, site['files'])}
{bar_script(p, site)}
</body>
</html>
"""


def render_draft(p, site, doc):
    for pat in STRIP_FROM_DRAFT:
        doc = re.sub(pat, "", doc, flags=re.I | re.S)
    doc = rewrite_links(doc, site["files"])
    block = "\n" + MARKER + "\n" + head_tags(p, site) + "\n"
    if re.search(r"<head[^>]*>", doc, re.I):
        doc = re.sub(r"(<head[^>]*>)", lambda m: m.group(1) + block, doc, count=1, flags=re.I)
    else:
        doc = "<!doctype html>\n<head>" + block + "</head>\n" + doc
    tail = bar_script(p, site) + "\n"
    i = doc.lower().rfind("</body>")
    return doc[:i] + tail + doc[i:] if i != -1 else doc + tail


def build(folder, name=None, base_url=None, noindex=None):
    folder = pathlib.Path(folder).resolve()
    if not folder.is_dir():
        sys.exit(f"Not a folder: {folder}")
    try:
        previous = json.loads(read(folder / "site.json") or "{}")
    except ValueError:
        previous = {}

    g = folder / "global"
    head = read(g / "01-site-head-code.html")
    header = read(g / "02-global-header.html")
    footer = read(g / "03-global-footer.html")
    pages = {p.stem: read(p) for p in sorted((folder / "pages").glob("*.html"))}
    drafts = {p.stem: read(p) for p in sorted((folder / "drafts").glob("*.html"))}
    if not pages and not drafts:
        sys.exit("Nothing to build: no pages/*.html and no drafts/*.html yet.")

    name = site_name(folder, name, previous)
    default_base = DEFAULT_HOST + urllib.parse.quote(folder.name) + "/"
    base = (base_url or previous.get("baseUrl") or default_base).rstrip("/") + "/"
    index_site = (not noindex) if noindex is not None else previous.get("index", True)

    slugs = sorted(set(pages) | set(drafts), key=page_order)
    home = "home" if "home" in slugs else slugs[0]
    files = {s: ("index.html" if s == home else f"{s}.html") for s in slugs}
    site = {"name": name, "base": base, "index": index_site, "files": files, "pages": []}

    seo_errors, seo_warnings = [], []
    for s in slugs:
        built = s in pages
        source = pages[s] if built else drafts[s]
        src_name = f"{'pages' if built else 'drafts'}/{s}.html"
        st = settings_from_comment(source) if built else settings_from_document(source)
        whole = (header + source + footer) if built else source
        indexable = s not in NEVER_INDEX
        title, desc = st["title"], st["description"]
        if indexable and index_site:
            if not title:
                seo_errors.append((src_name, "no SEO title written (add it to the page settings comment, or <title> in a draft)"))
            elif len(title) > 60:
                seo_warnings.append((src_name, f"SEO title is {len(title)} characters; keep it to 60 or fewer"))
            if not desc:
                seo_errors.append((src_name, "no meta description written (150 to 160 characters)"))
            elif not 70 <= len(desc) <= 165:
                seo_warnings.append((src_name, f"meta description is {len(desc)} characters; aim for 150 to 160"))
            h1 = len(re.findall(r"<h1\b", whole, re.I))
            if h1 != 1:
                seo_errors.append((src_name, f"{h1} <h1> elements; every page needs exactly one"))
            if not (st["image"] or first_image(source)):
                seo_warnings.append((src_name, "no social image (add \"Social image: https://...\" or an og:image)"))
        site["pages"].append({
            "slug": s, "label": label(s), "file": files[s], "built": built, "index": indexable,
            "title": title or (name if s == home else f"{label(s)} | {name}"),
            "description": desc or clip(visible_text(source)),
            "image": st["image"] or first_image(source),
            "lang": st.get("lang") or "en",
        })

    # write pages
    outputs = {}
    for p in site["pages"]:
        s = p["slug"]
        outputs[p["file"]] = (render_built(p, site, head, header, footer, pages[s]) if p["built"]
                              else render_draft(p, site, drafts[s]))
    today = datetime.date.today().isoformat()
    indexed = [p for p in site["pages"] if index_site and p["index"]]
    outputs["sitemap.xml"] = (
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{esc(base + ('' if p['file'] == 'index.html' else p['file']))}</loc><lastmod>{today}</lastmod></url>\n"
                  for p in indexed)
        + "</urlset>\n")

    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    for fname, content in outputs.items():
        target = folder / fname
        if target.exists() and fname.endswith(".html") and MARKER not in read(target):
            (folder / "archive").mkdir(exist_ok=True)
            shutil.move(str(target), str(folder / "archive" / f"{target.stem}-{stamp}.html"))
        target.write_text(content, encoding="utf-8")
    for stale in previous.get("generated", []):
        t = folder / stale
        if stale not in outputs and t.is_file() and t.parent == folder and (stale == "sitemap.xml" or MARKER in read(t)):
            t.unlink()

    # checks
    everything = "\n".join([head, header, footer, *pages.values(), *drafts.values()])
    digits = re.sub(r"\D", "", everything)
    mock_found = [what for what, hit in (
        ("address 001 NoWhere Avenue", "001 nowhere avenue" in everything.lower()),
        ("phone +1 999-999-9999", "19999999999" in digits or "999-999-9999" in everything),
        ("email info@mockup.ngynsolutions.com", "info@mockup.ngynsolutions.com" in everything.lower()),
    ) if hit]
    if mock_found and re.search(r"""["']@type["']\s*:\s*["'][A-Za-z]*(LocalBusiness|Store|Contractor|Dentist|Physician)["']""", everything):
        seo_warnings.append(("structured data", "business schema (LocalBusiness or similar) with mock contact details: "
                                                "leave it out of a mockup, add it back with real details at live handover"))
    broken, unlinked = check_links(header, footer, pages, drafts)

    updated = datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat()

    def entry(p):
        return {"slug": p["slug"], "label": p["label"], "url": p["file"], "title": p["title"],
                "description": p["description"], "index": bool(index_site and p["index"])}

    manifest = {
        "name": name,
        "prefix": folder.name.removesuffix("-ghl-site"),
        "entry": "index.html",
        "baseUrl": base,
        "index": index_site,
        "mock": bool(mock_found),
        "updated": updated,
        "pages": [entry(p) for p in site["pages"] if p["built"]],
        "drafts": [entry(p) for p in site["pages"] if not p["built"]],
        "seo": {"errors": [{"file": f, "problem": m} for f, m in seo_errors],
                "warnings": [{"file": f, "problem": m} for f, m in seo_warnings]},
        "linkCheck": {"broken": [{"file": f, "href": h, "problem": m} for f, h, m in broken], "unlinked": unlinked},
        "generated": sorted(outputs),
    }
    (folder / "site.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    built_n = sum(1 for p in site["pages"] if p["built"])
    print(f"Wrote {len(outputs) - 1} pages + sitemap.xml in {folder} ({built_n} built, {len(site['pages']) - built_n} drafts)")
    print(f"Public URL: {base}" + ("" if base_url or previous.get("baseUrl") else "  (default guess; pass --base-url if the published slug differs)"))
    print("Indexing: " + (f"ON, {len(indexed)} pages in sitemap.xml" if index_site else "OFF for the whole site (--noindex)"))
    if mock_found:
        print(f"MOCK DATA present ({'; '.join(mock_found)}). Correct for a mockup; replace before any live handover.")
    else:
        print("No mock contact details found. If this is a mockup, it must use them (references/mockup-legal.md).")
        if index_site:
            print("  If this site shows a real business identity, rebuild with --noindex.")
    for f, m in seo_warnings:
        print(f"SEO warning  {f}: {m}")
    if unlinked:
        print(f"WARNING: nothing links to: {', '.join(unlinked)} (reachable only through the preview bar)")
    failed = False
    if seo_errors:
        failed = True
        print(f"SEO ERRORS: {len(seo_errors)}. Fix every one before delivering:")
        for f, m in seo_errors:
            print(f"  {f}: {m}")
    else:
        print("SEO: every indexable page has a title, a description and one h1.")
    if broken:
        failed = True
        print(f"BROKEN LINKS: {len(broken)}. Fix every one before delivering:")
        for f, h, m in broken:
            print(f"  {f}: href=\"{h}\"  {m}")
    else:
        print("Links: all internal links resolve.")
    return 1 if failed else 0


